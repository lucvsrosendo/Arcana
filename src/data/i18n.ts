const localizedCardCache = new Map<string, TarotCard>();

const majorArcanaById = new Map(majorArcana.map((card) => [card.id, card]));

export const localizeCard = (card: TarotCard, language: LanguageCode): TarotCard => {
  const cacheKey = `${language}:${card.id}`;
  const cachedCard = localizedCardCache.get(cacheKey);

  if (cachedCard) {
    return cachedCard;
  }

  const text = cardTexts[language][card.id] ?? cardTexts.pt[card.id];
  const detail = arcanaDetails[card.id];

  const localizedCard = {
    ...card,
    ...text,
    keywords: [...text.positiveKeywords, ...text.cautionKeywords],
    symbols: detail?.symbols[language] ?? detail?.symbols.pt,
    correspondences: detail
      ? {
          element: detail.correspondences.element[language],
          planetOrSign: detail.correspondences.planetOrSign,
          hebrewLetter: detail.correspondences.hebrewLetter,
          path: detail.correspondences.path,
        }
      : undefined,
    image: card.image,
  };

  localizedCardCache.set(cacheKey, localizedCard);
  return localizedCard;
};

