export const getLocalizedSpreadDefinition = (
  spreadId: SpreadId,
  language: LanguageCode,
) => localizeSpread(getSpreadDefinition(spreadId), language);

export const getLocalizedSpreadDefinitions = (language: LanguageCode) =>
  spreadDefinitions.map((spread) => localizeSpread(spread, language));

export const localizeReadingSlots = (
  reading: readonly ReadingSlot[],
  spreadId: SpreadId,
  language: LanguageCode,
): ReadingSlot[] => {
  const spread = getLocalizedSpreadDefinition(spreadId, language);

  return reading.map((slot, index) => ({
    ...slot,
    position: spread.positions[index] ?? slot.position,
    card: localizeCard(slot.card, language),
  }));
};

export const localizeCombination = (
  combination: CardCombination,
  language: LanguageCode,
) => {
  const key = combination.cards.join("+");
  const text = combinationTexts[language][key] ?? combinationTexts.pt[key];
  const title = text?.title ?? combination.title;
  const interpretation = text?.interpretation ?? combination.interpretation;
  return `${title}: ${interpretation}`;
};

export const getLocalizedCombinationTextsForCardIds = (
  cardIds: readonly TarotCardId[],
  language: LanguageCode,
) => {
  const idSet = new Set(cardIds);

  return cardCombinations
    .filter((combination) => combination.cards.every((cardId) => idSet.has(cardId)))
    .map((combination) => localizeCombination(combination, language));
};

export const localizeReadingRecord = (
  record: ReadingRecord,
  language: LanguageCode,
): ReadingRecord => {
  const spread = getLocalizedSpreadDefinition(record.spreadId, language);

  return {
    ...record,
    spreadTitle: spread.title,
    combinations: getLocalizedCombinationTextsForCardIds(
      record.cards.map((card) => card.cardId),
      language,
    ),
    cards: record.cards.map((card, index) => {
      const arcana = majorArcanaById.get(card.cardId);
      const localizedCard = arcana ? localizeCard(arcana, language) : undefined;

      return {
        ...card,
        position: spread.positions[index]?.title ?? card.position,
        cardName: localizedCard?.name ?? card.cardName,
      };
    }),
  };
};
