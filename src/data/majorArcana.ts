import { getArcanaCardImage } from "../lib/artwork";
import type { ArcanaArtwork, TarotCard, TarotCardId } from "../types/tarot";

type CardSeed = Omit<TarotCard, "image" | "keywords"> & {
  artwork: ArcanaArtwork;
};

const buildCard = (card: CardSeed): TarotCard => ({
  ...card,
  keywords: [...card.positiveKeywords, ...card.cautionKeywords],
  image: getArcanaCardImage(card.id),
});

const card = (
  id: TarotCardId,
  number: number,
  name: string,
  description: string,
  positiveKeywords: string[],
  cautionKeywords: string[],
  meanings: TarotCard["meanings"],
  artwork: ArcanaArtwork,
) =>
  buildCard({
    id,
    number,
    name,
    description,
    positiveKeywords,
    cautionKeywords,
    meanings,
    artwork,
  });

